"""One-time helper: pull the photos that were embedded in the old single-file
index.html out into real image files.

Usage (needs Pillow):  python tools/extract_images.py path/to/old-index.html

Writes:
  assets/img/hero/<room>.webp        1600 px wide (hero slides)
  assets/img/hero/<room>-800.webp     800 px wide (space cards, mobile)
  assets/img/fixtures/<cat>-NN.webp       full size (detail dialog)
  assets/img/fixtures/<cat>-NN-480.webp   480 px wide (cards, pickers)
  og-image.jpg                        1200x630 link-preview image
  assets/js/fixture-tones.js          backdrop colours sampled from each photo

Re-create only the tones file from the existing images:
  python tools/extract_images.py --tones
"""
import base64, io, json, re, sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
HERO_NAMES = ["bedroom", "dining", "office", "balcony", "living"]  # order used by the old heroRooms array


def decode(uri):
    return Image.open(io.BytesIO(base64.b64decode(uri.split(",", 1)[1]))).convert("RGB")


def save(img, path, width=None, quality=78):
    if width and img.width > width:
        img = img.resize((width, round(img.height * width / img.width)), Image.LANCZOS)
    path.parent.mkdir(parents=True, exist_ok=True)
    img.save(path, "WEBP", quality=quality, method=6)
    return path.stat().st_size


def font(name, size):
    for candidate in (f"C:/Windows/Fonts/{name}", name):
        try:
            return ImageFont.truetype(candidate, size)
        except OSError:
            continue
    return ImageFont.load_default()


def make_og(hero, path):
    w, h = 1200, 630
    scale = max(w / hero.width, h / hero.height)
    img = hero.resize((round(hero.width * scale), round(hero.height * scale)), Image.LANCZOS)
    left, top = (img.width - w) // 2, (img.height - h) // 2
    img = img.crop((left, top, left + w, top + h)).convert("RGBA")
    shade = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    draw = ImageDraw.Draw(shade)
    for x in range(w):  # dark-to-clear gradient so the text stays readable
        alpha = round(225 * max(0.0, 1 - x / (w * 0.78)))
        draw.line([(x, 0), (x, h)], fill=(30, 26, 23, alpha))
    img = Image.alpha_composite(img, shade)
    draw = ImageDraw.Draw(img)
    draw.text((80, 190), "LumaDesign", font=font("georgiab.ttf", 44), fill=(239, 183, 79))
    draw.text((80, 262), "Find or create the", font=font("georgia.ttf", 68), fill=(255, 255, 255))
    draw.text((80, 342), "perfect lighting", font=font("georgia.ttf", 68), fill=(255, 255, 255))
    draw.text((80, 446), "Browse · Design · Preview in your room", font=font("segoeui.ttf", 28), fill=(232, 226, 214))
    img.convert("RGB").save(path, "JPEG", quality=84, optimize=True, progressive=True)
    return path.stat().st_size


def write_tones():
    """Sample the top and bottom edge colour of every fixture photo so the card
    behind it can use the same backdrop (no visible letterbox bands)."""
    def hexa(strip):
        return "#%02x%02x%02x" % strip.resize((1, 1), Image.BOX).getpixel((0, 0))

    tones = {}
    for path in sorted((ROOT / "assets/img/fixtures").glob("*-480.webp")):
        cat, num = path.stem.split("-")[:2]
        img = Image.open(path).convert("RGB")
        w, h = img.size
        band = max(2, h // 40)
        top = img.crop((0, 0, w, band))
        bottom = img.crop((0, h - band, w, h))
        tones.setdefault(cat, []).append([hexa(top), hexa(bottom)])
    out = ROOT / "assets/js/fixture-tones.js"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(
        "// Generated by tools/extract_images.py: [top, bottom] backdrop colour per fixture photo.\n"
        "window.LUMA_FIXTURE_TONES = " + json.dumps(tones, separators=(",", ":")) + ";\n",
        encoding="utf-8",
        newline="\n",
    )
    print(f"tones written for {sum(map(len, tones.values()))} fixtures")


def main(source):
    html = Path(source).read_text(encoding="utf-8")
    total = 0

    heroes = re.findall(r"image:'(data:image/jpeg;base64,[^']+)'", html)
    assert len(heroes) == len(HERO_NAMES), f"expected 5 hero images, found {len(heroes)}"
    for name, uri in zip(HERO_NAMES, heroes):
        img = decode(uri)
        total += save(img, ROOT / f"assets/img/hero/{name}.webp", 1600, 76)
        total += save(img, ROOT / f"assets/img/hero/{name}-800.webp", 800, 74)
        if name == "living":
            total += make_og(img, ROOT / "og-image.jpg")

    data = json.loads(re.search(r"const styleImageData=(\{.*?\});", html, re.S).group(1))
    ratios = []
    for cat, uris in data.items():
        for i, uri in enumerate(uris, 1):
            img = decode(uri)
            ratios.append(round(img.width / img.height, 3))
            total += save(img, ROOT / f"assets/img/fixtures/{cat}-{i:02d}.webp", None, 80)
            total += save(img, ROOT / f"assets/img/fixtures/{cat}-{i:02d}-480.webp", 480, 76)
        print(f"{cat}: {len(uris)} fixtures")
    print(f"aspect ratios (w/h): min {min(ratios)}, max {max(ratios)}")
    print(f"total written: {total / 1024:.0f} KB")
    write_tones()


if __name__ == "__main__":
    if "--tones" in sys.argv:
        write_tones()
        sys.exit()
    main(sys.argv[1] if len(sys.argv) > 1 else ROOT / "index.html")
